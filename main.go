type resultIndex struct {
	Engine       string
	Severity     string
	AlternateID  string
	SimilarityID string
	// PackageID is the SCA package identifier; only set for SCA results.
	PackageID string
	State     string
	// Result is the originating results.SAST / IAC / SCA entry, kept for its String() in log output.
	Result fmt.Stringer
}

// String describes the finding using the underlying result's own String(), falling back to the
// basic identifiers if no result is attached.
func (r resultIndex) String() string {
	if r.Result != nil {
		return r.Result.String()
	}
	return fmt.Sprintf("No linked result for %s %s %s", r.Engine, r.Severity, r.AlternateID)
}

// Process exit codes. This tool only runs after the scan has broken the pipeline's threshold,
// and nothing it does can clear that: AI Triage only ever proposes "Not Exploitable" (a human
// must still confirm), and remediations are only pull requests. So a completed run is never 0.
const (
	exitGateFailed = 1 // ran to completion; findings above threshold remain, so the pipeline must still fail
	exitUsage      = 2 // invalid flags (set by the flag package)
	exitError      = 3 // an operational failure (API, patch, or pull request error), or a fatal error
)

// operationErrors counts non-fatal failures (triage, remediation, patch or PR errors) in this run.
var operationErrors int

// recordError logs a non-fatal operational failure and remembers it for the exit code.
func recordError(logger *logrus.Logger, format string, args ...interface{}) {
	operationErrors++
	logger.Errorf(format, args...)
}

// exitCodeFor returns the process exit code for a run that completed: never 0.
func exitCodeFor(operationErrors int) int {
	if operationErrors > 0 {
		return exitError
	}
	return exitGateFailed
}

// finish ends the run with a non-zero exit code so the calling pipeline still fails.
func finish(logger *logrus.Logger) {
	code := exitCodeFor(operationErrors)
	if code == exitError {
		logger.Errorf("Finished with %d error(s); exiting with code %d", operationErrors, code)
	} else {
		logger.Warnf("Findings above the threshold remain (AI Triage only proposes a state and remediation needs a reviewed pull request); exiting with code %d so the pipeline fails", code)
	}
	os.Exit(code)
}

func main() {
	logger := logrus.New()
	logger.ExitFunc = func(int) { os.Exit(exitError) } // logger.Fatal* => operational/fatal error
	logger.SetLevel(logrus.InfoLevel)
	myformatter := &easy.Formatter{}
	myformatter.TimestampFormat = "2006-01-02 15:04:05.000"
	myformatter.LogFormat = "[%lvl%][%time%] %msg%\n"
	logger.SetFormatter(myformatter)
	logger.SetOutput(os.Stdout)

	logger.Info("Starting")
	LogLevel := flag.String("log", "INFO", "Log level: TRACE, DEBUG, INFO, WARNING, ERROR, FATAL")

	resultsFile := flag.String("input", "cx_result.json", "Path to JSON format report as generated by ast-cli --report-type json")
	numRemediate := flag.Int("remediate", 1, "Number of results to remediate, sorted by highest-priority and resultId")
	numTriage := flag.Int("triage", 0, "Number of results to triage, sorted by highest-priority and resultId")
	triageBatch := flag.Int("triageBatch", maxAIBatchSize, fmt.Sprintf("Number of results submitted to AI Triage together in one request (1-%d)", maxAIBatchSize))
	remediationBatch := flag.Int("remediationBatch", maxAIBatchSize, fmt.Sprintf("Number of results submitted to AI Remediation together in one request (1-%d)", maxAIBatchSize))
	engines := flag.String("engine", "sast,sca", "Focus only on these engines - comma separated list from: sast,sca")
	severity := flag.String("severity", "CRITICAL,HIGH", "Focus only on results of these severities - comma separated list from: CRITICAL,HIGH,MEDIUM,LOW,INFO")
	timeout := flag.Duration("timeout", 30*time.Minute, "Overall time limit for waiting on AI Triage and AI Remediation, e.g. 30m; 0 for no limit. Work that completes in time is still published as pull requests; unfinished work is abandoned and the run exits non-zero")
	sourceDir := flag.String("dir", ".", "Path to the root of the source code that was scanned, used as the base that remediation diffs are applied to in memory (never modified)")

	// repo-scope (classic PAT) or Contents+Pull-requests write (fine-grained) permissions
	githubToken := flag.String("githubToken", "", "GitHub token used to publish a pull request with the remediation changes (falls back to the GITHUB_TOKEN env var); required when using -remediate")
	repoFlag := flag.String("repo", "", "Target GitHub repository (owner/repo, https URL, or SSH URL) for the pull request; derived from the Checkmarx One project's repoUrl if omitted")
	baseBranchFlag := flag.String("baseBranch", "", "Branch to open the pull request against; defaults to the repository's default branch")
	prBranchFlag := flag.String("prBranch", "", "Prefix for the names of the branches created for pull requests; each branch is this prefix plus the engine and result ID (default \"cx1-remediate/\"). A finding whose branch already exists is skipped")

	proxy := flag.String("proxy", "", "Optional: Proxy server (http, https or socks5 URL) for outbound calls to Cx1 and GitHub; defaults to the HTTPS_PROXY environment variable")
	insecure := flag.Bool("insecure", false, "Optional: DISABLE TLS certificate verification for calls to Cx1 and GitHub (insecure; prefer -caCert)")
	caCert := flag.String("caCert", "", "Optional: Path to a PEM file with extra CA certificate(s) to trust for calls to Cx1 and GitHub, e.g. the CA of a TLS-inspecting proxy; added to the system trust store")

	noKeepAlive := flag.Bool("noKeepAlive", false, "Optional: Disable HTTP connection reuse (a new connection per request); use if a proxy drops pooled connections and calls fail with random EOF errors")

	// Cx1 authentication flags. These mirror Cx1ClientGo.NewClient, which can't be used here
	// because it parses the flags itself before the HTTP transport (which depends on -proxy,
	// -insecure and -caCert) can be built.
	apiKey := flag.String("apikey", "", "CheckmarxOne API Key (if not using client id/secret; falls back to CX_APIKEY)")
	clientID := flag.String("client", "", "CheckmarxOne Client ID (if not using API Key; falls back to CX_CLIENT_ID)")
	clientSecret := flag.String("secret", "", "CheckmarxOne Client Secret (if not using API Key; falls back to CX_CLIENT_SECRET)")
	cx1URL := flag.String("cx1", "", "CheckmarxOne platform URL (falls back to CX_BASE_URI)")
	iamURL := flag.String("iam", "", "CheckmarxOne IAM URL (falls back to CX_BASE_AUTH_URI)")
	tenant := flag.String("tenant", "", "CheckmarxOne tenant (falls back to CX_TENANT)")
	token := flag.String("token", "", "Optional: A valid access_token. If this value is provided, others will be ignored - the client will lose access when the token expires")
	userAgent := flag.String("useragent", "Cx1ClientGo", "Optional: A custom user-agent string for all requests to Cx1")

	flag.Parse()

	// Validate the arguments before connecting to anything or spending any AI credits.
	level, err := parseLogLevel(*LogLevel)
	if err != nil {
		usageError(logger, "Invalid -log: %s", err)
	}
	logger.SetLevel(level)

	*githubToken = valueOrEnv(*githubToken, "GITHUB_TOKEN")

	severities, err := parseSeverities(*severity)
	if err != nil {
		usageError(logger, "Invalid -severity: %s", err)
	}
	inScope, err := parseEngines(*engines)
	if err != nil {
		usageError(logger, "Invalid -engine: %s", err)
	}
	if *numTriage, err = checkCount(logger, "triage", *numTriage); err != nil {
		usageError(logger, "%s", err)
	}
	if *numRemediate, err = checkCount(logger, "remediate", *numRemediate); err != nil {
		usageError(logger, "%s", err)
	}
	// Remediations are only ever delivered as pull requests.
	if *numRemediate > 0 && *githubToken == "" {
		usageError(logger, "-remediate requires a GitHub token (-githubToken or GITHUB_TOKEN) to publish pull requests")
	}

	transport, err := newTransport(*proxy, *insecure, *caCert)
	if err != nil {
		logger.Fatalf("Invalid proxy/TLS configuration: %s", err)
	}
	transport.DisableKeepAlives = *noKeepAlive
	if *noKeepAlive {
		logger.Info("HTTP keep-alives disabled (-noKeepAlive)")
	}
	if *proxy != "" {
		logger.Infof("Using proxy")
	}
	if *insecure {
		logger.Warn("TLS certificate verification is DISABLED (-insecure); credentials and results can be intercepted. Prefer -caCert")
	}
	if *caCert != "" {
		logger.Infof("Trusting additional CA certificate(s) from %s", *caCert)
	}

	cx1client, err := Cx1ClientGo.NewClientWithOptions(Cx1ClientGo.Cx1ClientConfiguration{
		HttpClient:  &http.Client{Transport: transport},
		Logger:      logger,
		HTTPHeaders: http.Header{"User-Agent": []string{*userAgent}},
		Auth: Cx1ClientGo.Cx1ClientAuth{
			APIKey:       valueOrEnv(*apiKey, "CX_APIKEY"),
			ClientID:     valueOrEnv(*clientID, "CX_CLIENT_ID"),
			ClientSecret: valueOrEnv(*clientSecret, "CX_CLIENT_SECRET"),
			AccessToken:  *token,
		},
		Cx1Url: valueOrEnv(*cx1URL, "CX_BASE_URI"),
		IAMUrl: valueOrEnv(*iamURL, "CX_BASE_AUTH_URI"),
		Tenant: valueOrEnv(*tenant, "CX_TENANT"),
	})
	if err != nil {
		logger.Fatalf("Error creating client: %s", err)
	}
	logger.Infof("Connected with %v", cx1client.String())

	var scan Cx1ClientGo.Scan

	data, err := os.ReadFile(*resultsFile)
	if err != nil {
		logger.Fatalf("Failed to read report file %s: %s", *resultsFile, err)
	}

	scanId, count, results, err := cx1client.ParseReportJSON(data)
	if err != nil {
		logger.Fatalf("Failed to parse report file %s: %s", *resultsFile, err)
	}

	scan, err = cx1client.GetScanByID(scanId)
	if err != nil {
		logger.Fatalf("Failed to retrieve scan information for scan ID %s: %s", scanId, err)
	}
	logger.Infof("Target scan is %s", scan.String())

	// Pull requests are the only way remediations are delivered, so make sure they can be
	// created before any AI Triage or Remediation credits are spent.
	pr := prOptions{
		Token:      *githubToken,
		Transport:  transport,
		Repo:       *repoFlag,
		BaseBranch: *baseBranchFlag,
		Branch:     *prBranchFlag,
	}
	if *numRemediate > 0 {
		pr, err = preflightPR(context.Background(), logger, cx1client, &scan, pr, *sourceDir)
		if err != nil {
			code := exitError
			if errors.Is(err, errConfig) {
				code = exitUsage
			}
			logger.Errorf("Pull request preflight check failed: %s", err)
			os.Exit(code)
		}
	}

	inScopeCount := 0

	logger.Infof("Scan has %d SAST and %d SCA", len(results.SAST), len(results.SCA))

	if inScope.SAST {
		for _, r := range results.SAST {
			if severities[r.Severity] {
				inScopeCount++
			}
		}
	}
	if inScope.IAC {
		for _, r := range results.IAC {
			if severities[r.Severity] {
				inScopeCount++
			}
		}
	}
	if inScope.SCA {
		for _, r := range results.SCA {
			if severities[r.Severity] {
				inScopeCount++
			}
		}
	}

	if inScopeCount == 0 {
		logger.Warn("No results are in a supported engine/severity for AI Triage or Remediation; the threshold break must be resolved manually")
		finish(logger)
	}

	logger.Infof("Parsed scan ID %s report %s: %d results found with %d in scope", scanId, *resultsFile, count, inScopeCount)
	index := make([]resultIndex, inScopeCount)

	// internal priority list: SAST, IAC, SCA
	counter := 0
	if inScope.SAST {
		for _, r := range results.SAST {
			if !severities[r.Severity] {
				continue
			}
			index[counter] = resultIndex{
				Engine:       "sast",
				Severity:     r.Severity,
				AlternateID:  r.AlternateID,
				State:        r.State,
				SimilarityID: r.SimilarityID,
				Result:       r,
			}
			counter++
		}
	}

	if inScope.IAC {
		for _, r := range results.IAC {
			if !severities[r.Severity] {
				continue
			}
			index[counter] = resultIndex{
				Engine:       "iac",
				Severity:     r.Severity,
				AlternateID:  r.AlternateID,
				State:        r.State,
				SimilarityID: r.SimilarityID,
				Result:       r,
			}
			counter++
		}
	}

	if inScope.SCA {
		for _, r := range results.SCA {
			if !severities[r.Severity] {
				continue
			}
			index[counter] = resultIndex{
				Engine:       "sca",
				Severity:     r.Severity,
				AlternateID:  r.AlternateID,
				State:        r.State,
				SimilarityID: r.SimilarityID,
				Result:       r,
				PackageID:    r.Data.PackageIdentifier,
			}
			counter++
		}
	}

	if len(index) == 0 {
		logger.Warn("No results are in a supported engine/severity for AI Triage or Remediation; the threshold break must be resolved manually")
		finish(logger)
	}

	for i := range index {
		index[i].State = resolveState(logger, "Scan report entry "+index[i].String(), index[i].State, index[i].State)
	}

	slices.SortFunc(index, func(a, b resultIndex) int {
		sev := sevcmp(a.Severity, b.Severity)
		if sev != 0 {
			return sev
		}

		return cmp.Compare(a.AlternateID, b.AlternateID)
	})

	clientVars := cx1client.GetClientVars()
	aiBudget := newBudget(*timeout)
	if !aiBudget.unlimited() {
		logger.Infof("AI Triage and Remediation share an overall time limit of %s", *timeout)
	}

	if *numTriage > 0 {
		candidates := pickFindings(index, *numTriage, func(f *resultIndex) bool { return canTriage(logger, f) })
		batchSize := clampBatchSize(logger, "triageBatch", *triageBatch)
		logger.Infof("Will auto-triage %d results (requested %d) in batches of up to %d", len(candidates), *numTriage, batchSize)

		for batch := range slices.Chunk(candidates, batchSize) {
			if aiBudget.expired() {
				recordError(logger, "Overall -timeout of %s reached; not submitting further AI Triage batches", *timeout)
				break
			}
			triageBatchOf(cx1client, logger, &scan, batch, aiBudget, clientVars)
		}
	}

	if *numRemediate > 0 {
		// A finding whose branch already exists was remediated by an earlier run (its pull
		// request is open, or was closed without deleting the branch), so it is skipped and
		// the next finding takes its place.

		ghClient, owner, repo, err := githubTarget(pr)
		if err != nil {
			recordError(logger, "Cannot check for existing branches (%s); skipping AI Remediation", err)
			finish(logger)
			return
		}
		eligible := func(f *resultIndex) bool {
			if !isVerified(f) {
				return false
			}
			branch := branchFor(pr, f)
			exists, err := branchExists(context.Background(), ghClient, owner, repo, branch)
			switch {
			case err != nil:
				recordError(logger, "Could not check whether branch %q exists for %s: %s; skipping it", branch, f, err)
				return false
			case exists:
				logger.Infof("Skipping %s: branch %q already exists in %s/%s (remediated by an earlier run); delete the branch to retry", f, branch, owner, repo)
				return false
			}
			return true
		}

		candidates := pickFindings(index, *numRemediate, eligible)
		batchSize := clampBatchSize(logger, "remediationBatch", *remediationBatch)
		logger.Infof("Will auto-remediate %d results (requested %d, out of %d) in batches of up to %d", len(candidates), *numRemediate, len(index), batchSize)

		for batch := range slices.Chunk(candidates, batchSize) {
			if aiBudget.expired() {
				recordError(logger, "Overall -timeout of %s reached; not submitting further AI Remediation batches", *timeout)
				break
			}
			remediateBatchOf(cx1client, logger, &scan, batch, *sourceDir, pr, aiBudget, clientVars)
		}
	}

	finish(logger)
}

// The AI Triage / AI Remediation backends are only known to handle this many results per request.
const maxAIBatchSize = 5

// clampBatchSize forces a user-supplied batch size into the supported 1..maxAIBatchSize range.
func clampBatchSize(logger *logrus.Logger, name string, n int) int {
	switch {
	case n < 1:
		logger.Warnf("-%s must be at least 1, using 1", name)
		return 1
	case n > maxAIBatchSize:
		logger.Warnf("-%s capped at %d (requested %d)", name, maxAIBatchSize, n)
		return maxAIBatchSize
	}
	return n
}

// pickFindings returns pointers to the first limit findings (in the index's priority order)
// that satisfy eligible. The pointers alias index, so later state updates are visible to it.
func pickFindings(index []resultIndex, limit int, eligible func(*resultIndex) bool) []*resultIndex {
	var picked []*resultIndex
	for i := range index {
		if len(picked) >= limit {
			break
		}
		if eligible(&index[i]) {
			picked = append(picked, &index[i])
		}
	}
	return picked
}

// canTriage reports whether a finding should be submitted to AI Triage: it must still be
// TO_VERIFY, and an SCA finding must carry its package identifier, which is part of the job's
// key. Without it the platform has no such job, and polling would just wait out the timeout.
func canTriage(logger *logrus.Logger, f *resultIndex) bool {
	if f.State != stateToVerify {
		return false
	}
	if f.Engine == "sca" && (f.SimilarityID == "" || f.PackageID == "") {
		logger.Warnf("Skipping AI Triage for %s: the report entry has no similarity ID or package identifier", f)
		return false
	}
	return true
}

// isVerified reports whether a finding has been confirmed as a real issue, the only states
// eligible for AI Remediation. To_Verify, Not_Exploitable and the like are never remediated.
func isVerified(f *resultIndex) bool {
	return f.State == stateConfirmed || f.State == stateUrgent
}

// toBuckets groups findings by engine into the request format shared by the AI endpoints.
func toBuckets(findings []*resultIndex) []Cx1ClientGo.AIRequestBucket {
	var buckets []Cx1ClientGo.AIRequestBucket
	for _, f := range findings {
		i := slices.IndexFunc(buckets, func(b Cx1ClientGo.AIRequestBucket) bool { return b.Engine == f.Engine })
		if i < 0 {
			buckets = append(buckets, Cx1ClientGo.AIRequestBucket{Engine: f.Engine})
			i = len(buckets) - 1
		}
		buckets[i].AlternateIDs = append(buckets[i].AlternateIDs, f.AlternateID)
	}
	return buckets
}

// triageBatchOf submits the findings to AI Triage in a single request, then waits for each
// in turn. The jobs run concurrently on the platform, so only the first wait is long.
func triageBatchOf(cx1client *Cx1ClientGo.Cx1Client, logger *logrus.Logger, scan *Cx1ClientGo.Scan, batch []*resultIndex, aiBudget budget, vars Cx1ClientGo.ClientVars) {
	for _, finding := range batch {
		logger.Infof("AI Auto-Triage %s finding: %s", finding.Severity, finding)
	}

	triageId, err := cx1client.RequestAITriages(scan.ScanID, toBuckets(batch))
	if err != nil {
		recordError(logger, "Failed to request triage: %s", err)
		return
	}
	logger.Infof("AI Triage request ID: %s", triageId)

	for _, finding := range batch {
		var status string
		var err error
		delay, max := aiBudget.pollTimeouts(vars.AIPollingDelaySeconds, vars.AIPollingMaxSeconds)
		if finding.Engine == "sca" {
			status, err = cx1client.PollSCAAITriageStatusWithTimeout(scan.ProjectID, finding.SimilarityID, finding.PackageID, delay, max)
		} else {
			status, err = cx1client.PollSASTAITriageStatusWithTimeout(scan.ProjectID, finding.SimilarityID, delay, max)
		}
		if err != nil && aiBudget.expired() {
			recordError(logger, "Overall -timeout reached before AI Triage finished for %s (%s); its state is unchanged", finding, err)
			continue
		}
		if err != nil {
			// the job may have already finished while an earlier finding in the batch was being polled
			logger.Warnf("Failed while polling AI Triage for %s (%s); trying to fetch the result anyway", finding, err)
		} else {
			logger.Infof("AI Triage for %s finished with status: %s", finding, status)
		}

		if finding.Engine == "sca" {
			details, err := cx1client.GetSCAAITriage(scan.ScanID, scan.ProjectID, finding.SimilarityID, finding.PackageID)
			if err != nil {
				recordError(logger, "Failed to get AI Triage results for %s: %s", finding, err)
				continue
			}
			logger.Infof("AI Triage results: exploitability %s, reachability %s", details.Analysis.Exploitability.Status, details.Analysis.Reachability.Status)
			// an empty or unrecognized status leaves the state as-is (with a warning)
			finding.State = aiTriageState(logger, "AI Triage of "+finding.String(), details.Analysis.Exploitability.Status, details.Analysis.Reachability.Status, finding.State)
			continue
		}

		details, err := cx1client.GetSASTAITriage(scan.ProjectID, finding.SimilarityID)
		if err != nil {
			recordError(logger, "Failed to get AI Triage results for %s: %s", finding, err)
			continue
		}
		logger.Infof("AI Triage results: %s (reachability %s)", details.TriageStatus, details.ReachabilityStatus)
		finding.State = aiTriageState(logger, "AI Triage of "+finding.String(), details.TriageStatus, details.ReachabilityStatus, finding.State)
	}
}

// remediateBatchOf submits the findings to AI Remediation in a single request, then waits for
// each in turn and publishes its result. The jobs run concurrently on the platform, so only
// the first wait is long.
//
// Every remediation is computed in memory against the untouched source tree and published as
// its own independent pull request, so remediations that touch the same file do not interfere
// with one another. The source tree is never modified.
func remediateBatchOf(cx1client *Cx1ClientGo.Cx1Client, logger *logrus.Logger, scan *Cx1ClientGo.Scan, batch []*resultIndex, sourceDir string, pr prOptions, aiBudget budget, vars Cx1ClientGo.ClientVars) {
	for _, finding := range batch {
		logger.Infof("AI Auto-Remediate finding: %s", finding)
	}

	remediationId, err := cx1client.RequestAIRemediations(scan.ScanID, scan.ProjectID, toBuckets(batch))
	if err != nil {
		recordError(logger, "Failed to request remediation: %s", err)
		return
	}
	logger.Tracef("Requested remediation id: %s", remediationId)

	for _, finding := range batch {
		delay, max := aiBudget.pollTimeouts(vars.AIPollingDelaySeconds, vars.AIPollingMaxSeconds)
		status, err := cx1client.PollAIRemediationStatusWithTimeout(scan.ScanID, finding.Engine, finding.AlternateID, delay, max)
		if err != nil && aiBudget.expired() {
			// jobs that finished earlier still get their pull request; only this unfinished one is abandoned
			recordError(logger, "Overall -timeout reached before AI Remediation finished for %s (%s); abandoning it", finding, err)
			continue
		}
		if err != nil {
			// the job may have already finished while an earlier finding in the batch was being polled
			logger.Warnf("Failed while polling remediation for %s (%s); trying to fetch the result anyway", finding, err)
		} else {
			logger.Tracef("Remediation for %s finished with status: %s", finding, status)
		}

		details, err := cx1client.GetAIRemediationDetails(scan.ScanID, finding.AlternateID)
		if err != nil {
			recordError(logger, "Failed while retrieving remediation for %s %s finding %s: %s", finding.Severity, finding.Engine, finding, err)
			continue
		}

		changes, err := applyRemediationInMemory(logger, details, sourceDir)
		if err != nil {
			recordError(logger, "Skipping remediation for %s %s finding %s: %s", finding.Severity, finding.Engine, finding, err)
			continue
		}

		publishRemediationPR(logger, details, changes, pr, branchFor(pr, finding))
	}
}

var sevmap = map[string]int{
	"CRITICAL": 0,
	"HIGH":     1,
	"MEDIUM":   2,
	"LOW":      3,
	"INFO":     4,
}

// parseSeverities turns a comma-separated severity list (case-insensitive) into a set of backend severity values.
func parseSeverities(list string) (map[string]bool, error) {
	set := map[string]bool{}
	for _, s := range strings.Split(list, ",") {
		s = strings.ToUpper(strings.TrimSpace(s))
		if s == "" {
			continue
		}
		if _, ok := sevmap[s]; !ok {
			return nil, fmt.Errorf("unknown severity %q, expected any of CRITICAL,HIGH,MEDIUM,LOW,INFO", s)
		}
		set[s] = true
	}
	if len(set) == 0 {
		return nil, fmt.Errorf("no severities specified")
	}
	return set, nil
}

// prioritize findings by highest-severity first
func sevcmp(sev1, sev2 string) int {
	s1, ok1 := sevmap[sev1]
	s2, ok2 := sevmap[sev2]

	if ok1 && !ok2 {
		return -1
	}
	if ok2 && !ok1 {
		return 1
	}
	if !ok1 && !ok2 {
		return 0
	}

	if s1 < s2 {
		return -1
	}
	if s1 == s2 {
		return 0
	}
	return 1
}

// responseHeaderTimeout bounds the wait for a server's response headers after the request has
// been sent. It does not limit reading the body, so long-lived event streams are unaffected once
// they have started.
const responseHeaderTimeout = 120 * time.Second

// newTransport builds the HTTP transport for calls to Cx1. TLS verification stays on unless
// insecure is set; caCertFile adds extra trusted CAs (e.g. a TLS-inspecting proxy's) to the
// system pool.
func newTransport(proxy string, insecure bool, caCertFile string) (*http.Transport, error) {
	if insecure && caCertFile != "" {
		return nil, fmt.Errorf("-insecure and -caCert are mutually exclusive")
	}

	transport := http.DefaultTransport.(*http.Transport).Clone()
	// Go's default transport has no limit on how long a server may take to start responding,
	// so a server that accepts the connection and then stalls would hang the run forever.
	transport.ResponseHeaderTimeout = responseHeaderTimeout

	if proxy != "" {
		proxyURL, err := url.Parse(proxy)
		if err != nil || proxyURL.Scheme == "" || proxyURL.Host == "" {
			return nil, fmt.Errorf("invalid -proxy %q: expected a URL such as http://host:port", proxy)
		}
		transport.Proxy = http.ProxyURL(proxyURL)
	}

	switch {
	case insecure:
		transport.TLSClientConfig = &tls.Config{InsecureSkipVerify: true}
	case caCertFile != "":
		pem, err := os.ReadFile(caCertFile)
		if err != nil {
			return nil, fmt.Errorf("reading -caCert: %w", err)
		}
		pool, err := x509.SystemCertPool()
		if err != nil || pool == nil {
			pool = x509.NewCertPool()
		}
		if !pool.AppendCertsFromPEM(pem) {
			return nil, fmt.Errorf("-caCert %s contains no valid PEM certificates", caCertFile)
		}
		transport.TLSClientConfig = &tls.Config{RootCAs: pool}
	}

	return transport, nil
}

// valueOrEnv returns the flag value, or the first non-empty of the environment variables when
// the flag is empty. Values are whitespace-trimmed.
func valueOrEnv(flagValue string, envNames ...string) string {
	if v := strings.TrimSpace(flagValue); v != "" {
		return v
	}
	for _, name := range envNames {
		if v := strings.TrimSpace(os.Getenv(name)); v != "" {
			return v
		}
	}
	return ""
}

// usageError reports an invalid command line and exits with the usage code, before any
// network call or AI credit has been used.
func usageError(logger *logrus.Logger, format string, args ...interface{}) {
	logger.Errorf(format, args...)
	os.Exit(exitUsage)
}
